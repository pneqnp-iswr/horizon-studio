def icon(rows: list[str]) -> Canvas:
    if len(rows) != 16 or any(len(row) > 16 for row in rows):
        raise ValueError("icons are 16 rows of at most 16 cells")
    c = Canvas(16, 16)
    for y, row in enumerate(rows):
        for x, cell in enumerate(row):
            if cell == "#":
                c.set(x, y, INK)
    return c


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Fail if committed icons differ from a fresh render")
    args = parser.parse_args(argv)
    stale = []
    for name, (title, rows) in ICONS.items():
        svg = icon(rows).to_svg(1, title, f"Horizon Studio pixel icon: {title}")
        path = OUT / f"{name}.svg"
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != svg:
                stale.append(path)
            continue
        OUT.mkdir(parents=True, exist_ok=True)
        path.write_text(svg, encoding="utf-8", newline="\n")
    if stale:
        print("Stale UI icons (run python scripts/render_ui_icons.py):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    if not args.check:
        print(f"wrote {len(ICONS)} icons to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
