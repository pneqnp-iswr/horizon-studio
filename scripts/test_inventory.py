#!/usr/bin/env python3
"""Keep test counts in the documentation generated from the tests themselves.

    python scripts/test_inventory.py           # rewrite the marked sections
    python scripts/test_inventory.py --check   # fail when a marked section is stale

The browser and desktop E2E lists come from scripts/e2e_inventory.cjs (it loads the test files
without running them). Desktop E2E drives the real application window and is counted apart from
browser E2E and from the desktop smoke runs. Historical counts quoted for older commits are left alone; only the marked
"current master" sections are generated.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.roadmap import replace_section  # noqa: E402


def e2e_scenarios(suite: str = "e2e") -> list[dict]:
    node = shutil.which("node")
    if node is None:
        raise RuntimeError("node is required to list the E2E scenarios")
    out = subprocess.run([node, str(ROOT / "scripts" / "e2e_inventory.cjs"), suite], capture_output=True, text=True,
                         check=True, cwd=ROOT)
    return json.loads(out.stdout)


def listing(scenarios: list[dict]) -> str:
    rows = ["| File | Scenario |", "|---|---|"] + [f"| `{s['file']}` | {s['name']} |" for s in scenarios]
    return f"**{len(scenarios)} scenarios** on the current master (generated by `scripts/test_inventory.py`):\n\n" + "\n".join(rows)


def sections(scenarios: list[dict], desktop: list[dict]) -> dict[Path, list[tuple[str, str]]]:
    count = (f"- `browser-e2e`: **pass** — {len(scenarios)} scenarios on the current master (editor, workbench and "
             "roadmap explorer, PixelChat), Chromium on Ubuntu CI ([inventory](../BROWSER_E2E.md#current-inventory)). "
             "Firefox, WebKit and Windows browsers are not covered.")
    desktop_count = (f"- `desktop-e2e`: {len(desktop)} functional scenarios that drive the real application window through "
                     "tauri-driver: WebKitWebDriver on Linux, msedgedriver for WebView2 on Windows "
                     "([inventory](../DESKTOP.md#desktop-e2e)). They need a test build with the cargo feature `e2e`, "
                     "which answers the Save dialog from the environment; packaged builds are checked not to have it.")
    return {
        ROOT / "docs" / "BROWSER_E2E.md": [("e2e-inventory", listing(scenarios))],
        ROOT / "docs" / "DESKTOP.md": [("desktop-e2e-inventory", listing(desktop))],
        ROOT / "docs" / "roadmap" / "IMPLEMENTATION_STATUS.md": [("e2e-count", count), ("desktop-e2e-count", desktop_count)],
    }


def render(scenarios: list[dict], desktop: list[dict]) -> dict[Path, str]:
    files = {}
    for path, parts in sections(scenarios, desktop).items():
        text = path.read_text(encoding="utf-8")
        for name, body in parts:
            text = replace_section(text, name, body)
        files[path] = text
    return files


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for path, text in render(e2e_scenarios(), e2e_scenarios("desktop")).items():
        if path.read_text(encoding="utf-8") == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Stale test inventory (run python scripts/test_inventory.py):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
