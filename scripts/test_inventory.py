#!/usr/bin/env python3
"""Keep test counts in the documentation generated from the tests themselves.

    python scripts/test_inventory.py           # rewrite the marked sections
    python scripts/test_inventory.py --check   # fail when a marked section is stale

The browser E2E list comes from scripts/e2e_inventory.cjs (it loads the test files without
running them). Historical counts quoted for older commits are left alone; only the marked
"current master" sections are generated.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.roadmap import replace_section  # noqa: E402


def e2e_scenarios() -> list[dict]:
    node = shutil.which("node")
    if node is None:
        raise RuntimeError("node is required to list the browser E2E scenarios")
    out = subprocess.run([node, str(ROOT / "scripts" / "e2e_inventory.cjs")], capture_output=True, text=True,
                         check=True, cwd=ROOT)
    return json.loads(out.stdout)


def sections(scenarios: list[dict]) -> dict[Path, list[tuple[str, str]]]:
    rows = ["| File | Scenario |", "|---|---|"] + [f"| `{s['file']}` | {s['name']} |" for s in scenarios]
    listing = f"**{len(scenarios)} scenarios** on the current master (generated by `scripts/test_inventory.py`):\n\n" + "\n".join(rows)
    count = (f"- `browser-e2e`: **pass** — {len(scenarios)} scenarios on the current master (editor, workbench and "
             "roadmap explorer, PixelChat), Chromium on Ubuntu CI ([inventory](../BROWSER_E2E.md#current-inventory)). "
             "Firefox, WebKit and Windows browsers are not covered.")
    return {
        ROOT / "docs" / "BROWSER_E2E.md": [("e2e-inventory", listing)],
        ROOT / "docs" / "roadmap" / "IMPLEMENTATION_STATUS.md": [("e2e-count", count)],
    }


def render(scenarios: list[dict]) -> dict[Path, str]:
    files = {}
    for path, parts in sections(scenarios).items():
        text = path.read_text(encoding="utf-8")
        for name, body in parts:
            text = replace_section(text, name, body)
        files[path] = text
    return files


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for path, text in render(e2e_scenarios()).items():
        if path.read_text(encoding="utf-8") == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Stale test inventory (run python scripts/test_inventory.py):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
